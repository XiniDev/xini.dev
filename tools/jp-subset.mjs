// Keep only the Japanese/Chinese font slices the site actually draws, so a build ships a handful of files instead
// of ~240. Run it after adding or changing CJK text anywhere in src/: npm run jp-subset
// → src/shared/fonts/zen-kaku-700.css
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const files = [...walk(path.join(root, 'src')), path.join(root, 'index.html')].filter((f) => /\.(js|css|html)$/.test(f) && !f.endsWith('zen-kaku-700.css'));
const used = new Set();
for (const f of files) for (const ch of fs.readFileSync(f, 'utf8')) { const c = ch.codePointAt(0); if ((c >= 0x3000 && c <= 0x9fff) || (c >= 0xff00 && c <= 0xffef)) used.add(c); }
const css = fs.readFileSync(path.join(root, 'node_modules/@fontsource/zen-kaku-gothic-new/700.css'), 'utf8');
const blocks = css.split('/*').filter((b) => b.includes('@font-face'));
const inRange = (range, c) => range.split(',').some((r) => { const [a, b] = r.trim().replace('U+', '').split('-'); const lo = parseInt(a, 16), hi = b ? parseInt(b, 16) : lo; return c >= lo && c <= hi; });
const keep = blocks.filter((b) => { const m = b.match(/unicode-range:\s*([^;]+);/); return m && [...used].some((c) => inRange(m[1], c)); });
const out = keep.map((b) => '/*' + b.replace(/src:[^;]+;/, (s) => `src: url(../../../node_modules/@fontsource/zen-kaku-gothic-new/files/${s.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1]}) format('woff2');`)).join('');
fs.writeFileSync(path.join(root, 'src/shared/fonts/zen-kaku-700.css'), `/* Zen Kaku Gothic New 700, only the slices holding the ${used.size} characters the site draws. Generated by tools/jp-subset.mjs. */\n` + out);
console.log('chars', used.size, 'slices kept', keep.length, 'of', blocks.length);
